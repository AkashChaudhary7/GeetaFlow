export interface CuratedFeedOptions {
  isPremium?: boolean;
  moodFilter?: string | null;
  readVerseIds?: string[];
  refreshSeed?: number;
}

// Helper to build a continuous rich feed combining shlokas, situations, topics, intros, context, daily wisdom & ads
export function generateCuratedFeed(
  optionsOrPremium: boolean | CuratedFeedOptions = false,
  legacyMoodFilter: string | null = null
): Array<
  | { type: 'shloka'; data: Shloka; feedIndex: number }
  | { type: 'situation'; data: SituationCard; feedIndex: number }
  | { type: 'topic'; data: TopicCard; feedIndex: number }
  | { type: 'chapter_intro'; data: ChapterIntroCard; feedIndex: number }
  | { type: 'context'; data: ContextCard; feedIndex: number }
  | { type: 'daily_wisdom'; data: DailyWisdomCard; feedIndex: number }
  | { type: 'ad'; data: AdCard; feedIndex: number }
> {
  const options: CuratedFeedOptions = typeof optionsOrPremium === 'boolean'
    ? { isPremium: optionsOrPremium, moodFilter: legacyMoodFilter }
    : optionsOrPremium || {};

  const {
    isPremium = false,
    moodFilter = null,
    readVerseIds = [],
    refreshSeed = 0
  } = options;

  const now = new Date();
  const dayOfYear = Math.floor((now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / 86400000);
  const currentHour = now.getHours();

  // Combine calendar day + hour block + explicit refresh seed for pseudo-random session offset
  const hourBlock = Math.floor(currentHour / 4); // 6 distinct 4-hour blocks
  const effectiveSeed = Math.abs((dayOfYear * 7 + hourBlock * 13 + (refreshSeed % 1000)) | 0);

  const feed: Array<any> = [];
  let index = 0;

  // 1. Gather candidates from curated list
  let candidateShlokas: Shloka[] = [];

  if (moodFilter) {
    candidateShlokas = SHLOKAS_DATA.filter(s => 
      (Array.isArray(s.moods) && s.moods.includes(moodFilter)) || 
      (Array.isArray(s.topics) && s.topics.includes(moodFilter))
    );
    if (candidateShlokas.length === 0) {
      candidateShlokas = [...SHLOKAS_DATA];
    }
  } else {
    // Separate unread verses from already read verses to prioritize fresh discovery!
    const readSet = new Set(readVerseIds);
    const unreadList = SHLOKAS_DATA.filter(s => !readSet.has(s.id));
    const readList = SHLOKAS_DATA.filter(s => readSet.has(s.id));

    // Rotate array helper
    const rotateArray = <T>(arr: T[], offset: number): T[] => {
      if (arr.length <= 1) return arr;
      const safeOffset = Math.abs(offset % arr.length);
      return [...arr.slice(safeOffset), ...arr.slice(0, safeOffset)];
    };

    const rotatedUnread = rotateArray(unreadList, effectiveSeed);
    const rotatedRead = rotateArray(readList, effectiveSeed);

    // Combine unread first, followed by read
    candidateShlokas = [...rotatedUnread, ...rotatedRead];
    if (candidateShlokas.length === 0) {
      candidateShlokas = [...SHLOKAS_DATA];
    }
  }

  // Resanskrit Life Subhashitas (Life wisdom, health, peace, duty, motherland)
  const resanskritList = SHLOKAS_DATA.filter(s => s.id.startsWith('resanskrit_'));

  // Rotate rich non-shloka cards by effectiveSeed so cards are varied every session/day
  const sitLen = SITUATIONS_DATA.length;
  const dwLen = DAILY_WISDOM_DATA.length;
  const topLen = TOPICS_DATA.length;
  const introLen = CHAPTER_INTROS_DATA.length;
  const ctxLen = CONTEXT_CARDS_DATA.length;

  const sitOffset = effectiveSeed % Math.max(1, sitLen);
  const dwOffset = effectiveSeed % Math.max(1, dwLen);
  const topOffset = effectiveSeed % Math.max(1, topLen);
  const introOffset = effectiveSeed % Math.max(1, introLen);
  const ctxOffset = effectiveSeed % Math.max(1, ctxLen);

  // Card 0: Featured Shloka for this session (Never static)
  if (candidateShlokas.length > 0) {
    feed.push({ type: 'shloka', data: candidateShlokas[0], feedIndex: index++ });
  }

  // Card 1: Today's Dynamic Life Situation Card (Rotates each visit)
  if (sitLen > 0) {
    feed.push({ type: 'situation', data: SITUATIONS_DATA[sitOffset], feedIndex: index++ });
  }

  // Card 2: Second Shloka
  if (candidateShlokas.length > 1) {
    feed.push({ type: 'shloka', data: candidateShlokas[1], feedIndex: index++ });
  }

  // Card 3: Ad Card (if not premium)
  if (!isPremium && SAMPLE_ADS.length > 0) {
    feed.push({ type: 'ad', data: SAMPLE_ADS[effectiveSeed % SAMPLE_ADS.length], feedIndex: index++ });
  }

  // Card 4: Daily Wisdom / Reflection Card (Rotates each visit)
  if (dwLen > 0) {
    feed.push({ type: 'daily_wisdom', data: DAILY_WISDOM_DATA[dwOffset], feedIndex: index++ });
  }

  // Card 5: Resanskrit Life Wisdom Shloka (Subhashita)
  if (resanskritList.length > 0) {
    const resan1 = resanskritList[effectiveSeed % resanskritList.length];
    feed.push({ type: 'shloka', data: resan1, feedIndex: index++ });
  }

  // Card 6: Third Shloka
  if (candidateShlokas.length > 2) {
    feed.push({ type: 'shloka', data: candidateShlokas[2], feedIndex: index++ });
  }

  // Card 7: Topic Focus Card (Rotates each visit)
  if (topLen > 0) {
    feed.push({ type: 'topic', data: TOPICS_DATA[topOffset], feedIndex: index++ });
  }

  // Card 8: Second Resanskrit Life Wisdom Shloka
  if (resanskritList.length > 1) {
    const resan2 = resanskritList[(effectiveSeed + 1) % resanskritList.length];
    feed.push({ type: 'shloka', data: resan2, feedIndex: index++ });
  }

  // Card 9: Fourth Shloka
  if (candidateShlokas.length > 3) {
    feed.push({ type: 'shloka', data: candidateShlokas[3], feedIndex: index++ });
  }

  // Card 10: Scripture Context Card (Rotates each visit)
  if (ctxLen > 0) {
    feed.push({ type: 'context', data: CONTEXT_CARDS_DATA[ctxOffset], feedIndex: index++ });
  }

  // Card 11: Ad card (if not premium)
  if (!isPremium && SAMPLE_ADS.length > 1) {
    feed.push({ type: 'ad', data: SAMPLE_ADS[(effectiveSeed + 1) % SAMPLE_ADS.length], feedIndex: index++ });
  }

  // Card 12: Chapter Intro Card (Rotates each visit)
  if (introLen > 0) {
    feed.push({ type: 'chapter_intro', data: CHAPTER_INTROS_DATA[introOffset], feedIndex: index++ });
  }

  // 13+: Interleave remaining candidate shlokas, remaining situations, topics, and subhashitas
  let sCounter = 4;
  let resanCounter = 2;
  let loopStep = 0;

  while (sCounter < candidateShlokas.length) {
    // Add shloka
    feed.push({ type: 'shloka', data: candidateShlokas[sCounter++], feedIndex: index++ });
    loopStep++;

    // Interleave Resanskrit Subhashita every 3 steps
    if (loopStep % 3 === 0 && resanskritList.length > 0) {
      feed.push({ type: 'shloka', data: resanskritList[resanCounter % resanskritList.length], feedIndex: index++ });
      resanCounter++;
    }

    // Interleave remaining situations
    if (loopStep % 2 === 0 && sitLen > 0) {
      const nextSitIdx = (sitOffset + Math.floor(loopStep / 2)) % sitLen;
      feed.push({ type: 'situation', data: SITUATIONS_DATA[nextSitIdx], feedIndex: index++ });
    }

    // Interleave remaining topics
    if (loopStep % 4 === 0 && topLen > 0) {
      const nextTopIdx = (topOffset + Math.floor(loopStep / 4)) % topLen;
      feed.push({ type: 'topic', data: TOPICS_DATA[nextTopIdx], feedIndex: index++ });
    }

    // Interleave remaining daily wisdom
    if (loopStep % 5 === 0 && dwLen > 0) {
      const nextDwIdx = (dwOffset + Math.floor(loopStep / 5)) % dwLen;
      feed.push({ type: 'daily_wisdom', data: DAILY_WISDOM_DATA[nextDwIdx], feedIndex: index++ });
    }

    // Interleave ad if not premium
    if (!isPremium && loopStep % 6 === 0 && SAMPLE_ADS.length > 0) {
      feed.push({ type: 'ad', data: SAMPLE_ADS[loopStep % SAMPLE_ADS.length], feedIndex: index++ });
    }
  }

  return feed;
}
